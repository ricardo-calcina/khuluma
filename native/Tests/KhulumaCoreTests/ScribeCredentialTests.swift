/// A Keychain in memory; never the real one.
final class MemoryKeychain: ScribeKeychain, @unchecked Sendable {
  private let lock = NSLock()
  private var stored: String?
  var failOnSave = false
  init(_ key: String? = nil) { stored = key }
  func read() -> String? { lock.lock(); defer { lock.unlock() }; return stored }
  func save(_ key: String) throws {
    if failOnSave { throw CocoaError(.fileWriteUnknown) }
    lock.lock(); stored = key; lock.unlock()
  }
  func remove() throws { lock.lock(); stored = nil; lock.unlock() }
}

private func tempHome() throws -> URL {
  let url = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent("scribe-\(UUID().uuidString)", isDirectory: true)
  try FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
  return url
}

