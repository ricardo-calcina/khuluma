  @Test func matchesProvidersPy() throws {
    for c in Self.cases {
      let home = try tempHome()
      defer { try? FileManager.default.removeItem(at: home) }
      for (rel, content) in c.files {
        let url = home.appendingPathComponent(rel)
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try content.replacingOccurrences(of: "{HOME}", with: home.path).write(to: url, atomically: true, encoding: .utf8)
      }
      var env: [String: String] = [:]
      for (k, v) in c.env { env[k] = v.replacingOccurrences(of: "{HOME}", with: home.path) }
      let found = ScribeCredential(keychain: MemoryKeychain(), environment: env, home: home).lookup()
      #expect((found?.key ?? "") == c.expected, "\(c.name)")
    }
  }

  @Test func unreadableUTF8FileGivesNoKey() throws {
    let home = try tempHome()
    defer { try? FileManager.default.removeItem(at: home) }
    try (Data("export ELEVENLABS_API_KEY=abc".utf8) + [0xFF, 0x0A]).write(to: home.appendingPathComponent(".zshrc"))
    #expect(ScribeCredential(keychain: MemoryKeychain(), environment: [:], home: home).lookup() == nil)
  }

  @Test func reportsWhereTheKeyCameFrom() throws {
    let home = try tempHome()
    defer { try? FileManager.default.removeItem(at: home) }
    try "export ELEVENLABS_API_KEY=fromrc\n".write(to: home.appendingPathComponent(".zshrc"), atomically: true, encoding: .utf8)
    #expect(ScribeCredential(keychain: MemoryKeychain(), environment: [:], home: home).source == .shellSettings)
    #expect(ScribeCredential(keychain: MemoryKeychain(), environment: ["ELEVENLABS_API_KEY": "fromenv"], home: home).source == .environment)
    #expect(ScribeCredential(keychain: MemoryKeychain(), environment: [:], home: URL(fileURLWithPath: "/nonexistent")).source == nil)
  }

  @Test func shlexAndSplitLinesFollowPython() {
    #expect(Shlex.split(#"a "b c" 'd e' f\ g # x"#) == ["a", "b c", "d e", "f g"])
    #expect(Shlex.split(#""a\"b\\c\d""#) == [#"a"b\c\d"#])
    #expect(Shlex.split("'open") == nil)
    #expect(Shlex.split("trail\\") == nil)
    #expect(Shlex.split("") == [])
    #expect(PyText.splitLines("a\r\nb\rc\u{2028}d\n") == ["a", "b", "c", "d"])
    #expect(PyText.splitLines("a\n\nb") == ["a", "", "b"])
  }
}

struct ScribeCredentialLookupTests {
  @Test func keychainWinsOverEnvironmentAndShellSettings() throws {
    let home = try tempHome()
    defer { try? FileManager.default.removeItem(at: home) }
    try "export ELEVENLABS_API_KEY=fromrc\n".write(to: home.appendingPathComponent(".zshrc"), atomically: true, encoding: .utf8)
    let credential = ScribeCredential(keychain: MemoryKeychain("  fromkeychain\n"),
                                      environment: ["ELEVENLABS_API_KEY": "fromenv"], home: home)
    let found = credential.lookup()
    #expect(found?.key == "fromkeychain")
    #expect(found?.source == .keychain)
  }

  @Test func fallsBackWhenTheKeychainIsEmptyOrHoldsJunk() throws {
    let home = try tempHome()
    defer { try? FileManager.default.removeItem(at: home) }
    let env = ["ELEVEN_LABS_API_KEY": "fromenv"]
    #expect(ScribeCredential(keychain: MemoryKeychain(), environment: env, home: home).source == .environment)
    #expect(ScribeCredential(keychain: MemoryKeychain("   "), environment: env, home: home).source == .environment)
    #expect(ScribeCredential(keychain: MemoryKeychain("bad\u{1}key"), environment: env, home: home).source == .environment)
  }

  @Test func saveTrimsStoresAndRemoves() throws {
    let keychain = MemoryKeychain()
    let credential = ScribeCredential(keychain: keychain, environment: [:], home: URL(fileURLWithPath: "/nonexistent"))
    try credential.save("  typed-key \n")
    #expect(keychain.read() == "typed-key")
    #expect(credential.source == .keychain)
    try credential.removeStored()
    #expect(credential.source == nil)
    #expect(throws: ScribeCredential.Invalid.self) { try credential.save("   ") }
    #expect(throws: ScribeCredential.Invalid.self) { try credential.save("a\nb") }
    #expect(keychain.read() == nil)
  }

  @Test func settingsEnvironmentChecksTheKeyAtEachLoad() throws {
    var env = SettingsEnvironment(appFolder: URL(fileURLWithPath: "/tmp/a"), home: "/tmp/h", soundsDir: "/s", modelsDir: "/m",
                                  defaultSocketPath: "/sock", ffmpegAvailable: false, keyAvailable: false)
    let keychain = MemoryKeychain()
    let credential = ScribeCredential(keychain: keychain, environment: [:], home: URL(fileURLWithPath: "/nonexistent"))
    env.keyCheck = { credential.isAvailable }
    let store = AppSettings()
    #expect(AppConfig(settings: store, environment: env).transcription.keyAvailable == false)
    try keychain.save("abc")
    #expect(AppConfig(settings: store, environment: env).transcription.keyAvailable == true)
  }
}
